"""Roteiro: brief do comercial -> lista de planos prontos para virar nós no canvas.

Com modelo de texto: decupagem pela IA (planos, intenção em pt-BR, duração, movimento de câmera
escolhido entre os movimentos prontos do editor). Sem modelo: estruturas clássicas de comercial.
"""
from pydantic import BaseModel, Field

from . import llm, prompts
from .brand import CATEGORY_RULES, BrandKit

# Mesmos ids dos movimentos prontos do editor de câmera (static/js/camera.js).
CAMERA_PRESETS = {
    "static": "tripod, no movement", "push": "slow subtle push in", "dolly_in": "dolly in to detail",
    "reveal": "starts close and pulls back revealing", "truck": "lateral tracking", "pan": "pan sideways",
    "tilt": "tilt up revealing height", "crane": "crane rising, looking down", "orbit": "orbit around the subject",
    "push_pan": "push in while panning", "hero": "low-angle hero push in", "crash": "hold then fast crash zoom",
    "vertigo": "dolly zoom (vertigo)", "whip": "whip pan (good for cuts)", "roll": "dutch roll",
    "handheld": "handheld documentary shake",
}


class CastRef(BaseModel):
    name: str
    kind: str = "personagem"  # personagem | produto | estilo | logo
    desc: str = ""


class PlanRequest(BaseModel):
    brief: str
    duration: int = 15
    aspect: str = "16:9"
    max_shot: float = 5  # duração máxima por plano aceita pelos modelos de vídeo
    kit: BrandKit = Field(default_factory=BrandKit)
    cast: list[CastRef] = Field(default_factory=list)


STRUCTURES = {
    "short": [
        ("Gancho: produto herói", "{product} em destaque absoluto, luz de estúdio dramática, texturas e detalhes", 0.35, "hero"),
        ("Momento de uso", "pessoas aproveitando {product}, emoção genuína, clima {mood}", 0.40, "orbit"),
        ("Packshot e assinatura", "{product} no centro, fundo limpo nas cores {palette}, espaço para o logo", 0.25, "reveal"),
    ],
    "long": [
        ("Abertura: mundo da marca", "plano de estabelecimento de um lugar vibrante, clima {mood}, cores {palette}", 0.16, "crane"),
        ("Detalhe sensorial", "macro de {product}: textura, gotas, reflexos de luz", 0.14, "dolly_in"),
        ("Produto herói", "{product} como herói, luz volumétrica, acentos {palette}", 0.17, "orbit"),
        ("Conexão humana", "pessoas compartilhando um momento com {product}, emoção espontânea", 0.20, "handheld"),
        ("Clímax", "pico da celebração com {product}, partículas, câmera lenta", 0.15, "whip"),
        ("Packshot e assinatura", "{product} em packshot, fundo limpo {palette}, espaço para logo e texto legal", 0.18, "push"),
    ],
}


def _rules(req: PlanRequest) -> list[dict]:
    k = req.kit
    structure = STRUCTURES["short" if req.duration <= 15 else "long"]
    out = []
    for name, tpl, w, cam in structure:
        intent = tpl.format(product=k.product or "o produto", palette=k.palette or "da marca", mood=k.mood or "premium")
        out.append({"name": name, "intent": intent, "duration": req.duration * w, "camera": cam, "why": ""})
    return out


SYSTEM = (
    "You are the director of a TV/social commercial. Break the brief into shots that will each be generated by an "
    "AI video model (one continuous shot each, no cuts inside a shot). Reply JSON: "
    '{"title":"pt-BR campaign title","shots":[{"name":"pt-BR 2-5 words","intent":"pt-BR, 1-3 sentences describing '
    'exactly what is seen and what moves; mention the brand/product by name; mention recurring characters/products by '
    'their given names","duration":seconds,"camera":"one preset id","why":"pt-BR, why this shot/camera (short)"}],'
    '"notes":"pt-BR, one sentence about the edit rhythm"}. '
    "Rules: total duration close to the requested; each shot between 2s and the max shot length; start with a hook "
    "in the first 2 seconds; end with a packshot/brand signature; vary camera presets; product shots keep the product "
    "rigid and unchanged (motion from camera and environment)."
)


def plan(req: PlanRequest) -> dict:
    k = req.kit
    ctx = "\n".join(x for x in [
        f"Brief (pt-BR): {req.brief}",
        f"Total duration: {req.duration}s. Max shot length: {req.max_shot}s. Format: {req.aspect}.",
        f"Brand: '{k.brand}'. Product (visual): {k.product}. Palette: {k.palette}. Mood: {k.mood}. Category: {k.category}.",
        f"Forbidden terms: {', '.join(k.forbidden)}" if k.forbidden else "",
        *[f"Recurring {c.kind} named '{c.name}': {c.desc}" for c in req.cast],
        f"Camera presets (id: meaning): {CAMERA_PRESETS}",
    ] if x)
    data = llm.chat_json(prompts.get("director"), ctx)
    shots = (data or {}).get("shots")
    source = llm.source()
    if not isinstance(shots, list) or not shots:
        shots, source, data = _rules(req), "estrutura clássica (sem modelo de texto)", {}
    out = []
    for i, s in enumerate(shots[:12], 1):
        cam = s.get("camera") if s.get("camera") in CAMERA_PRESETS else "push"
        dur = min(float(req.max_shot), max(2.0, float(s.get("duration") or 3)))
        out.append({"index": i, "name": str(s.get("name") or f"Plano {i}")[:60], "intent": str(s.get("intent") or ""),
                    "duration": round(dur, 1), "camera": cam, "why": str(s.get("why") or "")})
    rule = CATEGORY_RULES.get(k.category)
    return {"title": (data or {}).get("title") or "", "shots": out, "notes": (data or {}).get("notes") or "",
            "source": source, "compliance_note": rule["note"] if rule else None,
            "total": round(sum(s["duration"] for s in out), 1)}
