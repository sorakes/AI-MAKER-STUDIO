"""SECRET_KEY: fallback automático gera WARNING; com a variável definida não há aviso."""
import logging

from app import config


def test_autogenerated_key_logs_warning(monkeypatch, tmp_path, caplog):
    monkeypatch.delenv("SECRET_KEY", raising=False)
    monkeypatch.setattr(config, "DATA_DIR", tmp_path)
    with caplog.at_level(logging.WARNING, logger="ai_studio"):
        key = config._secret_key()
    assert key and (tmp_path / ".secret_key").exists()
    warns = [r for r in caplog.records if r.levelno == logging.WARNING and "SECRET_KEY" in r.getMessage()]
    assert warns, "esperava WARNING de SECRET_KEY autogerada"


def test_fallback_warns_on_every_start(monkeypatch, tmp_path, caplog):
    monkeypatch.delenv("SECRET_KEY", raising=False)
    monkeypatch.setattr(config, "DATA_DIR", tmp_path)
    config._secret_key()
    with caplog.at_level(logging.WARNING, logger="ai_studio"):
        config._secret_key()  # segundo start: arquivo já existe, aviso continua
    assert any("NÃO DEFINIDA" in r.getMessage() for r in caplog.records)


def test_explicit_key_has_no_warning(monkeypatch, tmp_path, caplog):
    monkeypatch.setenv("SECRET_KEY", "minha-chave-forte")
    monkeypatch.setattr(config, "DATA_DIR", tmp_path)
    with caplog.at_level(logging.WARNING, logger="ai_studio"):
        assert config._secret_key() == "minha-chave-forte"
    assert not [r for r in caplog.records if "SECRET_KEY" in r.getMessage()]
